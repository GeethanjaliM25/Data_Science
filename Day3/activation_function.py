import numpy as np

# 1. Binary Step Function
def binary_step(x):
    return np.where(x >= 0, 1, 0)

print("--- Binary Step Function ---")
print("Formula: f(x) = 1 if x >= 0, else 0")
inputs = np.arange(-10, 11)
outputs = binary_step(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11}")

# 2. Sigmoid Function
def sigmoid(x):
    return 1 / (1 + np.exp(-x))

print("\n--- Sigmoid Function ---")
print("Formula: f(x) = 1 / (1 + e^(-x))")
inputs = np.arange(-10, 11, dtype=float)
outputs = sigmoid(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11.6f}")

# 3. Tanh Function
def tanh(x):
    return np.tanh(x)

print("\n--- Tanh Function ---")
print("Formula: f(x) = (e^x - e^(-x)) / (e^x + e^(-x))")
inputs = np.arange(-10, 11, dtype=float)
outputs = tanh(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11.6f}")

# 4. ReLU (Rectified Linear Unit) Function
def relu(x):
    return np.maximum(0, x)

print("\n--- ReLU Function ---")
print("Formula: f(x) = max(0, x)")
inputs = np.arange(-10, 11, dtype=float)
outputs = relu(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11.6f}")

# 5. Leaky ReLU Function
def leaky_relu(x, alpha=0.01):
    return np.where(x > 0, x, x * alpha)

print("\n--- Leaky ReLU Function (alpha=0.01) ---")
print("Formula: f(x) = x if x > 0, else alpha * x")
inputs = np.arange(-10, 11, dtype=float)
outputs = leaky_relu(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11.6f}")

# 6. ELU (Exponential Linear Unit) Function
def elu(x, alpha=1.0):
    return np.where(x > 0, x, alpha * (np.exp(x) - 1))

print("\n--- ELU Function (alpha=1.0) ---")
print("Formula: f(x) = x if x > 0, else alpha * (e^x - 1)")
inputs = np.arange(-10, 11, dtype=float)
outputs = elu(inputs)
print("Input (x) | Output f(x)")
print("-----------------------")
for i, o in zip(inputs, outputs):
    print(f"{i:9} | {o:11.6f}")

