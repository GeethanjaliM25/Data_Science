# Custom Activation Function: Smooth Linear Softplus (SLS)
# This function aims to combine the linearity of ReLU for positive inputs
# with a smooth, non-zero gradient for negative inputs, inspired by Softplus,
# while ensuring differentiability at x=0.

# Formula:
# f(x) = x                  if x >= 0
# f(x) = 2 * log(1 + e^x)   if x < 0
# The factor of 2 ensures differentiability at x=0, as derivative of x is 1,
# and derivative of log(1+e^x) is sigmoid(x). At x=0, sigmoid(0) = 0.5.
# So, 2 * 0.5 = 1.

def custom_activation_sls(x):
    return np.where(x >= 0, x, 2 * np.log(1 + np.exp(x)))

# Generate input range
x_custom = np.linspace(-10, 10, 400)
y_custom = custom_activation_sls(x_custom)

