def create_cnn_model(input_shape, num_classes, activation_hidden='relu'):
    model = keras.Sequential([
        layers.Conv2D(32, (3, 3), activation=activation_hidden, input_shape=input_shape),
        layers.MaxPooling2D((2, 2)),
        layers.Conv2D(64, (3, 3), activation=activation_hidden),
        layers.MaxPooling2D((2, 2)),
        layers.Flatten(),
        layers.Dense(128, activation=activation_hidden),
        layers.Dense(num_classes, activation='softmax') # Softmax for multi-class classification
    ])
    model.compile(optimizer='adam', loss='categorical_crossentropy', metrics=['accuracy'])
    return model

