print(f"Original y_train shape: {y_train.shape}")

# Normalize pixel values to 0-1 range
x_train = x_train.astype('float32') / 255.0
x_test = x_test.astype('float32') / 255.0

# Reshape images to vectors (28*28 = 784 pixels)
x_train = x_train.reshape(-1, 28 * 28)
x_test = x_test.reshape(-1, 28 * 28)

# Convert labels to one-hot encoding
y_train = keras.utils.to_categorical(y_train, num_classes=10)
y_test = keras.utils.to_categorical(y_test, num_classes=10)

print(f"x_train (reshaped and normalized) shape: {x_train.shape}")
print(f"y_train (one-hot encoded) shape: {y_train.shape}")
print("Data preprocessing complete.")

import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
import time

# Function to create a simple neural network model
def create_model(activation_function):
    model = keras.Sequential([
        layers.Input(shape=(784,)),
        layers.Dense(128, activation=activation_function),
        layers.Dense(64, activation=activation_function),
        layers.Dense(10, activation='softmax') # Output layer for 10 classes
    ])

    model.compile(
        optimizer='adam',
        loss='categorical_crossentropy',
        metrics=['accuracy']
    )
    return model

# Common training parameters
epochs = 10
batch_size = 32

# Dictionary to store results for comparison
results = {}

