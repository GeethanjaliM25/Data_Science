print("Advantages of Smooth Linear Softplus (SLS) compared to ReLU:")
print("1. Smoothness: SLS is a continuously differentiable function across its entire domain, unlike ReLU which has a non-differentiable point at x=0. Smoothness is often beneficial for gradient-based optimization.")
print("2. No 'Dead ReLU' Problem: For negative inputs, SLS provides a non-zero, positive gradient (2 * sigmoid(x)). This ensures that neurons with negative inputs can still learn and contribute to the gradient, mitigating the 'dead ReLU' problem where neurons can get stuck for negative inputs.")

