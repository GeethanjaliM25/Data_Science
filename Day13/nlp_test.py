"""## Practical Task 2: Social Media Text Cleaning

This task requires an additional step: removing hashtags and mentions. I'll create a specialized function for this and apply it to the sample social media comments.
"""

def clean_social_media_text(text):
    # Apply general cleaning first
    text = clean_text_general(text)

    # Remove hashtags and mentions
    text = re.sub(r'#\w+', '', text)  # Remove hashtags
    text = re.sub(r'@\w+', '', text)  # Remove mentions

    # Remove any extra spaces that might result from removal
    text = re.sub(r'\s+', ' ', text).strip()
    return text

