import re
import nltk
from nltk.corpus import stopwords
from collections import Counter
import pandas as pd

# Download NLTK stopwords if not already downloaded
try:
    nltk.data.find('corpora/stopwords')
except nltk.downloader.DownloadError:
    nltk.download('stopwords')

stop_words = set(stopwords.words('english'))

"""## General Text Cleaning Function

This function will perform case folding, contraction expansion, special character removal, stopword removal, and extra space removal. This function will be reused across various tasks.
"""

# The 'contractions' dictionary is already available in the kernel state.

def clean_text_general(text):
    # 1. Case Folding
    text = text.lower()

    # 2. Expand Contractions
    # Use a regex to find all contractions in the text and replace them
    for contraction, expansion in contractions.items():
        text = re.sub(r'\b' + re.escape(contraction) + r'\b', expansion, text)

    # 3. Remove Special Characters (keep alphanumeric and spaces)
    text = re.sub(r'[^a-z0-9\s]', '', text)

    # 4. Remove Stopwords
    words = text.split()
    words = [word for word in words if word not in stop_words]
    text = ' '.join(words)

    # 5. Remove Unnecessary Extra Spaces
    text = re.sub(r'\s+', ' ', text).strip()

    return text

"""## Practical Task 1: Text Cleaning Pipeline

Here, I'll apply the `clean_text_general` function to the sample input, display the original and cleaned text, and calculate the number of words before and after preprocessing.
"""

sample_input_task1 = "I'm really HAPPY about this product!!! It's amazing & I don't\nthink I've ever used something this good. @product #awesome"

# Clean the text
cleaned_text_task1 = clean_text_general(sample_input_task1)

# Calculate word counts
words_before_task1 = len(sample_input_task1.split())
